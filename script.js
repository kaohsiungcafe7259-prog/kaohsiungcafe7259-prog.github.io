const LANG_KEY = "hanzixu-lang";
const button = document.querySelector(".language-toggle");
const command = document.querySelector("#typed-command");
const reduceMotion = window.matchMedia
  ? window.matchMedia("(prefers-reduced-motion: reduce)").matches
  : false;
let language = "zh";
let typing = 0;

function readStoredLanguage() {
  try {
    return window.localStorage.getItem(LANG_KEY);
  } catch (error) {
    return null;
  }
}

function writeStoredLanguage(value) {
  try {
    window.localStorage.setItem(LANG_KEY, value);
  } catch (error) {
    // file:// preview or private browsing: the choice simply won't persist.
  }
}

function typeCommand(text) {
  window.clearInterval(typing);
  if (reduceMotion) {
    command.textContent = text;
    return;
  }
  let index = 0;
  command.textContent = "";
  typing = window.setInterval(() => {
    index += 1;
    command.textContent = text.slice(0, index);
    if (index >= text.length) {
      window.clearInterval(typing);
    }
  }, 38);
}

function render() {
  const c = copy[language];
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const text = c[el.dataset.i18n];
    if (typeof text === "string") {
      el.innerHTML = text;
    }
  });
  button.textContent = language === "zh" ? "EN" : "中文";
  button.setAttribute(
    "aria-label",
    language === "zh" ? "Switch to English / 切换到英文" : "Switch to Chinese / 切换到中文"
  );
  typeCommand(c.command);
}

button.addEventListener("click", () => {
  language = language === "zh" ? "en" : "zh";
  render();
  writeStoredLanguage(language);
});

document.querySelector("#year").textContent = new Date().getFullYear();
language = readStoredLanguage() === "en" ? "en" : "zh";
render();
